// Builds the component registry from components/gallery/<slug>/.
// Each folder needs meta.ts (export const meta) and demo.tsx (default export),
// and may have tokens.css. Run automatically before dev and build.
import { readdirSync, existsSync, writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const dir = join(root, "components/gallery");
const slugs = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(dir, d.name, "meta.ts")))
  .map((d) => d.name);

const num = (slug) => {
  const m = /number:\s*(\d+)/.exec(readFileSync(join(dir, slug, "meta.ts"), "utf8"));
  return m ? +m[1] : 999;
};
slugs.sort((a, b) => num(a) - num(b));

const id = (slug) => slug.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const header = "// AUTO-GENERATED by scripts/gen-registry.mjs. Do not edit by hand.\n";

writeFileSync(
  join(root, "lib/registry.ts"),
  header +
    'import type { ComponentMeta } from "./types";\n' +
    slugs.map((s) => `import { meta as ${id(s)} } from "@/components/gallery/${s}/meta";`).join("\n") +
    "\n\nexport const components: ComponentMeta[] = [\n" +
    slugs.map((s) => `  ${id(s)},`).join("\n") +
    "\n];\n\nexport const getComponent = (slug: string) => components.find((c) => c.slug === slug);\n"
);

writeFileSync(
  join(root, "lib/demos.ts"),
  header +
    'import type { ComponentType } from "react";\n' +
    slugs.map((s) => `import ${id(s)} from "@/components/gallery/${s}/demo";`).join("\n") +
    "\n\nexport type DemoProps = { embed?: boolean };\n\nexport const demos: Record<string, ComponentType<DemoProps>> = {\n" +
    slugs.map((s) => `  "${s}": ${id(s)},`).join("\n") +
    "\n};\n"
);

writeFileSync(
  join(root, "app/tokens.css"),
  "/* AUTO-GENERATED by scripts/gen-registry.mjs */\n" +
    slugs
      .filter((s) => existsSync(join(dir, s, "tokens.css")))
      .map((s) => `@import "../components/gallery/${s}/tokens.css";`)
      .join("\n") +
    "\n"
);

console.log(`registry: ${slugs.length} components`);
